def extract_reviews_by_tags(
    tags: list[str],
    countries: list[str],
    start_date: date,
    end_date: date,
    api_key: str,
    db_path: str = DEFAULT_DB,
    max_games_per_tag: int = 10,
    min_reviews: int = 0,
    appids: list[str] | None = None,
    passes: int = 1,
    game_delay: float = GAME_DELAY,
    review_database: str | None = None,
    allow_unverified_cache: bool = False,
    profile_database: str | None = None,
    profile_max_batches: int | None = None,
    profile_max_runtime: float | None = None,
    refresh_profiles: bool = False,
) -> pd.DataFrame:
    """
    Full pipeline:
        1. Local catalog → app IDs per tag
        2. Steam API     → reviews per app
        3. GetPlayerSummaries → country_code per user (batched)
        4. Filter known countries while retaining unresolved country records
        5. Return structured DataFrame

    Output columns:
        app_id, app_name, recommendation_id, review_version, review_content_hash,
        user_id, country_code, country_status, language, review_text, voted_up,
        tag, date_created
    """
    catalog, catalog_metadata = load_catalog_with_metadata(db_path)
    all_rows        = []
    game_metadata: list[dict] = []
    seen_appids: set[str] = set()
    countries_upper = [c.upper() for c in countries]

    def build_metadata(country_metadata: dict | None = None) -> dict:
        games_complete = bool(game_metadata) and all(
            game["complete"] for game in game_metadata
        )
        country_complete = (
            country_metadata is None or country_metadata.get("complete", False)
        )
        return {
            "schema_version": 1,
            "created_at": datetime.now(tz=timezone.utc).isoformat(),
            "software": software_metadata(),
            "query": {
                "tags": tags,
                "appids": [str(appid) for appid in appids] if appids else None,
                "countries": countries_upper,
                "language": "all",
                "start_date": start_date.isoformat(),
                "end_date": end_date.isoformat(),
                "passes_requested": passes,
                "selection_mode": "explicit_appids" if appids else "tag_top_reviews",
                "max_games": max_games_per_tag,
                "min_reviews": min_reviews,
                "steam_filter": "recent",
                "offtopic_included": False,
                "review_database": review_database,
                "profile_database": profile_database,
                "profile_max_batches": profile_max_batches,
                "profile_max_runtime": profile_max_runtime,
                "refresh_profiles": refresh_profiles,
                "allow_unverified_cache": allow_unverified_cache,
            },
            "catalog": {**catalog_metadata, "path": db_path},
            "games": game_metadata,
            "country_enrichment": country_metadata,
            "dataset_complete": games_complete and country_complete,
        }

    # ------------------------------------------------------------------
    # Steps 1 & 2: discover games and collect reviews
    # ------------------------------------------------------------------
    tags_label = " & ".join(tags)

    if not appids:
        games_list = get_appids_by_tags(tags, catalog, min_reviews=min_reviews)
        games_list = games_list[:max_games_per_tag]
    else:
        games_list = []

    if not games_list and not appids:
        log.warning(f"No games found matching all tags: {tags}")
        df = pd.DataFrame()
        df.attrs["extraction_metadata"] = build_metadata()
        return df

    tag = tags_label

    # Handle --appids: build games_list from explicit appids if provided
    if appids:
        games_list = [
            {
                "appid": str(appid),
                "name":  catalog.get(str(appid), {}).get("name", f"App {appid}"),
                "reviews": (
                    (catalog.get(str(appid), {}).get("positive") or 0)
                    + (catalog.get(str(appid), {}).get("negative") or 0)
                ),
            }
            for appid in appids
        ]

    if not games_list:
        log.warning(f"No games found matching all tags: {tags}")
        df = pd.DataFrame()
        df.attrs["extraction_metadata"] = build_metadata()
        return df

    log.info(f"[Tags: {tags_label}] Processing {len(games_list)} games")

    for i, game in enumerate(games_list, start=1):
        appid        = game["appid"]
        name         = game["name"]
        already_seen = appid in seen_appids
        seen_appids.add(appid)

        log.info(f"  [{i}/{len(games_list)}] {name} (appid: {appid})" + (" [already collected]" if already_seen else ""))

        if already_seen:
            time.sleep(game_delay)
            continue

        reviews = None
        cached_metadata = None
        if review_database:
            with ReviewStore(review_database) as store:
                verified_cache = store.has_coverage(appid, "all", start_date, end_date)
                unverified_cache = (
                    allow_unverified_cache
                    and not verified_cache
                    and store.has_unverified_job_coverage(
                        appid, "all", start_date, end_date
                    )
                )
                if verified_cache or unverified_cache:
                    reviews = store.get_reviews(appid, start_date, end_date, language="all")
                    coverage = store.get_coverage(appid, "all", "recent")
                    cached_metadata = {
                        "complete": verified_cache,
                        "completion_reason": (
                            "local_database_coverage"
                            if verified_cache
                            else "local_database_unverified_coverage"
                        ),
                        "passes_executed": 0,
                        "unique_reviews_in_date_range": len(reviews),
                        "drift_detected": False,
                        "passes": [],
                        "source": "sqlite_cache",
                        "archive": {
                            "database": review_database,
                            "coverage": coverage,
                            "coverage_verified": verified_cache,
                        },
                    }
                    log.info(
                        f"  → using {len(reviews):,} cached reviews from '{review_database}'"
                    )
                else:
                    log.info(
                        f"  → local database has no complete coverage for this interval; "
                        f"falling back to Steam"
                    )

        if reviews is None:
            extraction = fetch_reviews_with_metadata(
                appid=appid,
                language="all",
                start_date=start_date,
                end_date=end_date,
                passes=passes,
            )
            reviews = extraction.reviews
            extraction_metadata = {**extraction.to_metadata(), "source": "steam_api"}
        else:
            extraction_metadata = cached_metadata

        game_metadata.append({
            "appid": str(appid),
            "name": name,
            "catalog_reviews": game.get("reviews"),
            **extraction_metadata,
        })

        for r in reviews:
            author = r.get("author", {})
            ts     = r.get("timestamp_created")
            date_created = (
                datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%d/%m/%Y")
                if ts else None
            )
            all_rows.append({
                "app_id":       appid,
                "app_name":     name,
                "recommendation_id": r.get("recommendationid"),
                "review_version": r.get("_archive_version", 1),
                "review_content_hash": r.get(
                    "_archive_content_hash", review_content_hash(r)
                ),
                "user_id":      author.get("steamid"),
                "country_code": None,
                "language":     r.get("language", ""),
                "review_text":  r.get("review"),
                "voted_up":     r.get("voted_up"),
                "tag":          tags_label,
                "date_created": date_created,
            })

        log.info(f"  → {len(reviews)} reviews collected")
        time.sleep(game_delay)

    if not all_rows:
        log.warning("No reviews collected. Check tags and date range.")
        df = pd.DataFrame()
        df.attrs["extraction_metadata"] = build_metadata()
        return df

    df = pd.DataFrame(all_rows)

    # ------------------------------------------------------------------
    # Step 3: enrich with country_code via GetPlayerSummaries
    # ------------------------------------------------------------------
    unique_users = df["user_id"].dropna().unique().tolist()
    profile_store_path = profile_database or review_database
    if profile_store_path:
        with ReviewStore(profile_store_path) as profile_store:
            country_result = fetch_country_codes_with_metadata(
                unique_users,
                api_key,
                store=profile_store,
                max_batches=profile_max_batches,
                max_runtime=profile_max_runtime,
                refresh_profiles=refresh_profiles,
            )
    else:
        country_result = fetch_country_codes_with_metadata(
            unique_users,
            api_key,
            max_batches=profile_max_batches,
            max_runtime=profile_max_runtime,
            refresh_profiles=refresh_profiles,
        )
    df["country_code"] = df["user_id"].map(country_result.country_map).fillna("")
    status_map = country_result.status_map or {
        steam_id: (
            "country_available" if country else "country_unavailable"
        )
        for steam_id, country in country_result.country_map.items()
    }
    df["country_status"] = (
        df["user_id"].map(status_map).fillna("not_checked")
    )
    reviews_before_country_filter = len(df)
    available_country = df["country_status"] == "country_available"

    def coverage_by(column: str) -> dict[str, dict]:
        summary = {}
        for value, group in df.groupby(column, dropna=False):
            total = len(group)
            statuses = group["country_status"]
            available = int((statuses == "country_available").sum())
            unavailable = int((statuses == "country_unavailable").sum())
            profile_unavailable = int((statuses == "profile_unavailable").sum())
            request_failed = int((statuses == "request_failed").sum())
            not_checked = int((statuses == "not_checked").sum())
            classified = available + unavailable + profile_unavailable
            attempted = classified + request_failed
            summary[str(value or "unknown")] = {
                "reviews_total": total,
                "attempted_reviews": attempted,
                "classified_reviews": classified,
                "country_available_reviews": available,
                "country_unavailable_reviews": unavailable,
                "profile_unavailable_reviews": profile_unavailable,
                "request_failed_reviews": request_failed,
                "not_checked_reviews": not_checked,
                "processing_coverage_percent": round(
                    classified / total * 100, 2
                ),
                "country_availability_among_classified_percent": (
                    round(available / classified * 100, 2)
                    if classified
                    else 0.0
                ),
            }
        return summary

    review_status_counts = {
        str(status): int(count)
        for status, count in df["country_status"].value_counts().items()
    }
    author_status_counts = {
        str(status): int(count)
        for status, count in pd.Series(
            unique_users, dtype="object"
        ).map(status_map).fillna("not_checked").value_counts().items()
    }
    country_distribution = {
        str(country): int(count)
        for country, count in df.loc[
            available_country, "country_code"
        ].value_counts().items()
    }
    df["_review_year"] = df["date_created"].str[-4:].fillna("unknown")
    language_coverage = coverage_by("language")
    year_coverage = coverage_by("_review_year")
    df.drop(columns=["_review_year"], inplace=True)

    # ------------------------------------------------------------------
    # Step 4: filter by country
    # ------------------------------------------------------------------
    if countries_upper:
        before = len(df)
        country_matches = df["country_code"].isin(countries_upper)
        unresolved = df["country_status"] != "country_available"
        matched_reviews = int(country_matches.sum())
        unresolved_reviews = int((~country_matches & unresolved).sum())
        df = df[country_matches | unresolved]
        log.info(
            "Filter: retained %s/%s reviews (%s matching %s; %s with unavailable "
            "or pending country)",
            len(df),
            before,
            matched_reviews,
            ", ".join(countries_upper),
            unresolved_reviews,
        )
    else:
        matched_reviews = len(df)
        unresolved_reviews = int(
            (df["country_status"] != "country_available").sum()
        )

    country_metadata = country_result.to_metadata()
    country_metadata["reviews_before_filter"] = reviews_before_country_filter
    country_metadata["author_status_counts"] = author_status_counts
    country_metadata["review_status_counts"] = review_status_counts
    country_metadata["known_country_distribution_reviews"] = country_distribution
    country_metadata["coverage_by_language"] = language_coverage
    country_metadata["coverage_by_year"] = year_coverage
    country_metadata["reviews_matching_filter"] = matched_reviews
    country_metadata["reviews_unresolved_retained"] = unresolved_reviews
    country_metadata["reviews_after_filter"] = len(df)
    df.attrs["extraction_metadata"] = build_metadata(country_metadata)

    if df.empty:
        log.warning("No reviews left after country filter.")
        return df

    # ------------------------------------------------------------------
    # Step 5: summary
    # ------------------------------------------------------------------
    log.info(f"Done. Total rows: {len(df):,}")
    log.info("\n" + df.groupby(["tag", "country_code"]).size().to_string())

    return df


