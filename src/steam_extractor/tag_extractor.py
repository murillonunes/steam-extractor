def positive_int(value: str) -> int:
    parsed = int(value)
    if parsed < 1:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return parsed


def positive_float(value: str) -> float:
    parsed = float(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return parsed


def main():
    parser = argparse.ArgumentParser(
        description="Tag Extractor — collects Steam reviews by genre/category and country.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Build catalog first (once):
  python3 steamspy_catalog_fetcher.py

  # MVP test:
  python3 tag_extractor.py --tags Action --countries BR US \
      --start 01/12/2025 --end 31/12/2025 \
      --max-games 2 --api-key YOUR_KEY

  # Larger run:
  python3 tag_extractor.py --tags Action FPS Singleplayer \
      --countries BR US --start 01/01/2024 --end 31/12/2024 \
      --max-games 10 --api-key YOUR_KEY
        """
    )

    parser.add_argument("--tags",        nargs="+", required=True,
                        help="Genre or category names (e.g. Action FPS Singleplayer)")
    parser.add_argument("--countries",   nargs="+", default=[],
                        help="ISO country codes to keep (e.g. BR US). Omit to keep all.")
    parser.add_argument("--start",       required=True, help="Start date dd/mm/yyyy")
    parser.add_argument("--end",         required=True, help="End date dd/mm/yyyy")
    parser.add_argument("--api-key",     default=None,
                        help="Steam Web API key (or set STEAM_API_KEY env var)")
    parser.add_argument("--db",          default=DEFAULT_DB,
                        help=f"Path to local SteamSpy catalog (default: {DEFAULT_DB})")
    parser.add_argument("--review-db",   default=None,
                        help="Optional SQLite review archive; reuse it when coverage is complete")
    parser.add_argument(
        "--profile-db",
        default=None,
        help="SQLite profile cache (default: --review-db, or steam_profiles.sqlite)",
    )
    parser.add_argument(
        "--profile-max-batches",
        type=positive_int,
        default=None,
        metavar="N",
        help="Pause profile enrichment after N API batches; completed batches are cached",
    )
    parser.add_argument(
        "--profile-max-runtime",
        type=positive_float,
        default=None,
        metavar="SECONDS",
        help="Pause profile enrichment after this wall-clock duration",
    )
    parser.add_argument(
        "--refresh-profiles",
        action="store_true",
        help="Query terminal cached profiles again instead of reusing them",
    )
    parser.add_argument("--allow-unverified-cache", action="store_true",
                        help="Allow resumed SQLite coverage that could not be fully verified; "
                             "the manifest will mark the dataset incomplete")
    parser.add_argument("--appids",       nargs="+", default=None,
                        help="Specific app IDs to collect (skips catalog tag lookup)")
    parser.add_argument("--max-games",   type=int, default=10,
                        help="Max games per tag when not using --appids (default: 10)")
    parser.add_argument("--min-reviews", type=int, default=0,
                        help="Min total reviews a game must have to be included (default: 0)")
    parser.add_argument("--format",      choices=["csv", "json"], default="csv",
                        help="Output format (default: csv)")
    parser.add_argument("--output",      default=None,
                        help="Output filename without extension (auto-generated if omitted)")
    parser.add_argument("--passes",      type=int, default=1, metavar="N",
                        help="Collection passes per game merged via deduplication (default: 1). "
                             "Use 3+ to recover reviews missed by cursor drift.")
    parser.add_argument("--game-delay",  type=float, default=GAME_DELAY, metavar="S",
                        help=f"Seconds to wait between games (default: {GAME_DELAY}). "
                             "Increase to reduce session throttling when processing "
                             "multiple high-volume games.")

    args = parser.parse_args()

    api_key = args.api_key or os.environ.get("STEAM_API_KEY")
    if not api_key:
        print("Error: Steam API key required. Use --api-key or set STEAM_API_KEY env var.")
        return 1

    log_file = setup_logging()
    log.info(f"Log file: {log_file}")

    try:
        start_date = parse_date(args.start)
        end_date   = parse_date(args.end)
        if start_date > end_date:
            raise ValueError("--start must be before or equal to --end")
    except ValueError as e:
        log.error(f"Date error: {e}")
        return 1

    log.info("=" * 55)
    log.info("Steam Extractor v8.0.0")
    log.info(f"Tags     : {', '.join(args.tags)}")
    log.info(f"Countries: {', '.join(args.countries) if args.countries else 'all'}")
    log.info(f"Period   : {args.start} -> {args.end}")
    log.info(f"Max games: {args.max_games} per tag")
    log.info(f"Catalog  : {args.db}")
    log.info("=" * 55)

    df = extract_reviews_by_tags(
        tags=args.tags,
        countries=args.countries,
        start_date=start_date,
        end_date=end_date,
        api_key=api_key,
        db_path=args.db,
        max_games_per_tag=args.max_games,
        min_reviews=args.min_reviews,
        appids=args.appids,
        passes=args.passes,
        game_delay=args.game_delay,
        review_database=args.review_db,
        allow_unverified_cache=args.allow_unverified_cache,
        profile_database=args.profile_db or args.review_db or DEFAULT_PROFILE_DB,
        profile_max_batches=args.profile_max_batches,
        profile_max_runtime=args.profile_max_runtime,
        refresh_profiles=args.refresh_profiles,
    )

    if args.output:
        output_name = args.output
    else:
        tags_slug      = "_".join(args.tags).lower()
        countries_slug = "_".join(args.countries).lower() or "all"
        safe_start     = args.start.replace("/", "-")
        safe_end       = args.end.replace("/", "-")
        output_name    = f"reviews_{tags_slug}_{countries_slug}_{safe_start}_{safe_end}"

    save_output(df, output_name, args.format)
    return 0


if __name__ == "__main__":
    main()
