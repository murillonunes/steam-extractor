def load_catalog_with_metadata(db_path: str) -> tuple[dict, dict]:
    """Loads games and metadata from a local SteamSpy catalog."""
    path = Path(db_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Steam catalog not found at '{db_path}'.\n"
            f"Run first: python3 steamspy_catalog_fetcher.py"
        )

    with open(path, encoding="utf-8") as f:
        data = json.load(f)

    games = data.get("games", {})
    meta  = data.get("metadata", {})
    log.info(f"Catalog loaded: {len(games):,} games from '{db_path}' (downloaded: {meta.get('downloaded_at', 'unknown')})")
    return games, meta


def load_catalog(db_path: str) -> dict:
    """Backward-compatible helper returning only games from the catalog."""
    games, _metadata = load_catalog_with_metadata(db_path)
    return games


def get_appids_by_tags(
    tags: list[str],
    games: dict,
    min_reviews: int = 0,
) -> list[dict]:
    """
    Filters the local SteamSpy catalog by multiple user tags (AND logic)
    and minimum review count. A game must have ALL specified tags to be included.
    Results are sorted by total reviews descending (most reviewed first).

    Args:
        tags:        list of user tag names (e.g. ['FPS', 'Multiplayer'])
        games:       dict loaded from steamspy_catalog.json
        min_reviews: minimum total reviews (positive + negative, default: 0)

    Returns:
        List of dicts with keys: appid, name — sorted by review count desc.
    """
    tags_lower = [t.lower() for t in tags]
    log.info(f"Filtering for tags: {tags} (AND, min reviews: {min_reviews:,})")
    filtered = []

    for appid, info in games.items():
        game_tags = [t.lower() for t in info.get("tags", {}).keys()]
        total     = (info.get("positive") or 0) + (info.get("negative") or 0)

        if all(t in game_tags for t in tags_lower) and total >= min_reviews:
            filtered.append({
                "appid":   appid,
                "name":    info.get("name", "Unknown"),
                "reviews": total,
            })

    filtered.sort(key=lambda g: g["reviews"], reverse=True)
    log.info(f"Found {len(filtered)} games matching all tags with >= {min_reviews:,} reviews")
    return filtered


