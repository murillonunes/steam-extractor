#!/usr/bin/env python3

"""
Tag Extractor - Extracts Steam reviews grouped by genre tags and country.

Builds on steam_extractor.py: uses a local Steam catalog (generated by
steamspy_catalog_fetcher.py) to discover app IDs by user tag, then
calls the Steam API to collect reviews and enriches each review with the
author's country via GetPlayerSummaries.

Output schema: app_id | app_name | user_id | country_code | language |
               review_text | voted_up | tag | date_created

Usage:
    # First, build the local catalog (once):
    python3 steamspy_catalog_fetcher.py

    # Then extract reviews:
    python3 tag_extractor.py --tags Action FPS --countries BR US \
        --start 01/01/2023 --end 31/12/2023 \
        --api-key YOUR_KEY
"""

