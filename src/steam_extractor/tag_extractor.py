def save_output(df: pd.DataFrame, filename: str, format_type: str = "csv") -> None:
    """Saves the DataFrame to CSV or JSON."""
    metadata = df.attrs.get("extraction_metadata")
    if df.empty:
        log.warning("Nothing to save.")
        if metadata is not None:
            metadata["output"] = {"rows": 0, "format": format_type, "file": None}
            manifest_file = save_manifest(filename, metadata)
            log.info(f"Saved metadata: {manifest_file}")
        return

    path = f"{filename}.{format_type}"
    if format_type == "json":
        df.to_json(path, orient="records", force_ascii=False, indent=2)
    else:
        df.to_csv(path, index=False, encoding="utf-8")

    log.info(f"Saved: {path} ({len(df):,} rows)")
    if metadata is not None:
        metadata["output"] = {"rows": len(df), "format": format_type, "file": path}
        manifest_file = save_manifest(filename, metadata)
        log.info(f"Saved metadata: {manifest_file}")


